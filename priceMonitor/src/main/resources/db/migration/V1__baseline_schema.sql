-- Baseline: the schema Hibernate used to create from the Product and PricePoint
-- entities (ddl-auto=update), now owned by Flyway.
-- Standard SQL only, so the same file runs on PostgreSQL and on H2 (tests).

CREATE TABLE product (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title         VARCHAR(500),
    current_price DOUBLE PRECISION,
    last_checked  TIMESTAMP(6) WITH TIME ZONE,
    url           VARCHAR(2048) NOT NULL,
    CONSTRAINT uk_product_url UNIQUE (url)
);

CREATE TABLE price_point (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT           NOT NULL,
    price      DOUBLE PRECISION NOT NULL,
    checked_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT fk_price_point_product FOREIGN KEY (product_id) REFERENCES product (id)
);

-- Price history is always read per product, ordered by time.
CREATE INDEX idx_price_point_product_checked_at ON price_point (product_id, checked_at);
